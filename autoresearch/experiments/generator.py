"""Experiment code generation workflow."""
from __future__ import annotations
import logging
from typing import Any, Dict, TYPE_CHECKING
from .spec import ExperimentSpec

if TYPE_CHECKING:
    from ..config.schema import AutoResearchConfig

logger = logging.getLogger(__name__)


class ExperimentGenerator:
    def __init__(self, config: "AutoResearchConfig") -> None:
        self.config = config

    def generate(self, hypothesis: Dict[str, Any], topic: str) -> ExperimentSpec:
        """Generate an experiment spec from a hypothesis."""
        hyp_id = hypothesis.get("id", "hyp_0")
        title = hypothesis.get("title", f"Experiment for {topic}")
        code = self._generate_code(hypothesis, topic)
        return ExperimentSpec(
            hypothesis_id=hyp_id,
            title=title,
            description=f"Automated experiment testing: {title}",
            code=code,
            language="python",
            dependencies=["numpy", "scipy"],
            timeout_seconds=self.config.experiment.timeout_seconds,
            max_retries=self.config.experiment.max_retries,
            provenance={"hypothesis": hypothesis, "topic": topic},
        )

    def _generate_code(self, hypothesis: Dict[str, Any], topic: str) -> str:
        return f"""# AutoResearch v2 — Generated experiment
# Hypothesis: {hypothesis.get('title', topic)}
# Generated by ExperimentGenerator

import json
import sys

def run_experiment():
    \"\"\"Minimal baseline experiment scaffold.\"\"\"
    results = {{
        "hypothesis_id": "{hypothesis.get('id', 'unknown')}",
        "topic": "{topic}",
        "metrics": {{"baseline_score": 0.5, "status": "completed"}},
        "log": "Experiment ran successfully",
    }}
    print(json.dumps(results))
    return results

if __name__ == "__main__":
    run_experiment()
"""
